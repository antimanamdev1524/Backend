s= "program is very easy for programmer"


print(s.capitalize())     #1 first letter capital of any sentence
print(s.casefold())       #2 lowercase all letters of sentences
print(s.center(50, "-"))  #3 to cover sentences length upto 40 use - 
print(s.count("m"))       #4 count how many letters in given sentences
print(s.find("e"))        #5 show letter position  index start from 0
print(s.index("g"))       #6 show letter position index start from zero
print(s.isalnum())        #7 it will be show boolean result as true or false
print(s.isalpha())        #8 it will be show boolean result if all is alphabetical
print(s.isascii())        #9 ascii
print(s.islower())        #10 show boolean result if all is in lowercase
print(s.swapcase())          #11 swap case into upper or lower
print(s.replace("m", "x"))   #12 replace m with x
print(s.title())             #13  show title means sentance into uppercase

